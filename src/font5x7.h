// 特殊符号字形
// 度符号: 顶部 4x4 圆环 (bit0=最上行)
//   col0=0x06 行1,2   col1=0x09 行0,3   col2=0x09 行0,3   col3=0x06 行1,2
static const uint8_t FONT_DEG_GLYPH[5] = {0x06, 0x09, 0x09, 0x06, 0x00};
static const uint8_t FONT_BLK_GLYPH[5] = {0x7E, 0x7E, 0x7E, 0x7E, 0x7E};
static const uint8_t FONT_UP_GLYPH[5] = {0x08, 0x0C, 0x7F, 0x0C, 0x08};
static const uint8_t FONT_DN_GLYPH[5] = {0x08, 0x30, 0x7F, 0x30, 0x08};
static const uint8_t FONT_BUL_GLYPH[5] = {0x00, 0x18, 0x18, 0x00, 0x00};

inline const uint8_t *fontGlyph(char ch) {
  uint8_t c = (uint8_t)ch;
  if (c >= 32 && c <= 95)
    return FONT5X7[c - 32];
  switch (c) {
  case (uint8_t)FONT_DEG:
    return FONT_DEG_GLYPH;
  case (uint8_t)FONT_BLK:
    return FONT_BLK_GLYPH;
  case (uint8_t)FONT_UP:
    return FONT_UP_GLYPH;
  case (uint8_t)FONT_DN:
    return FONT_DN_GLYPH;
  case (uint8_t)FONT_BUL:
    return FONT_BUL_GLYPH;
  default:
    return FONT5X7[0];
  }
}

